// Extracts the icons from the design mock-up (ref/design.png) and traces them to SVG paths.
// Run with: node scripts/trace-icons.mjs [--debug]
// Output: app/_lib/traced-icons.ts
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import potrace from "potrace";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const REF = path.join(ROOT, "ref", "design.png");
const DEBUG = process.argv.includes("--debug");
const DBG = path.join(ROOT, "ref", "debug");
if (DEBUG) mkdirSync(DBG, { recursive: true });

const img = sharp(REF).ensureAlpha();
const { width: W } = await img.metadata();
const raw = await img.raw().toBuffer();
const px = (x, y) => {
  const i = (y * W + x) * 4;
  return [raw[i], raw[i + 1], raw[i + 2]];
};

// alpha 0..1 for "this pixel belongs to the icon"
const redAlpha = ([r, g, b]) => Math.max(0, Math.min(1, (r - Math.max(g, b) - 40) / 110));
const whiteAlpha = ([r, g, b]) => Math.max(0, Math.min(1, (Math.min(r, g, b) - 95) / 110));

/** find horizontal groups of "on" columns inside a band */
function groups(band, alphaFn, { gap, minW = 8 }) {
  const { x0, x1, y0, y1 } = band;
  const cols = [];
  for (let x = x0; x < x1; x++) {
    let on = false;
    for (let y = y0; y < y1; y++) if (alphaFn(px(x, y)) > 0.5) { on = true; break; }
    cols.push(on);
  }
  const out = [];
  let start = null, last = null;
  for (let i = 0; i < cols.length; i++) {
    if (cols[i]) {
      if (start === null) start = i;
      else if (i - last > gap) { out.push([start, last]); start = i; }
      last = i;
    }
  }
  if (start !== null) out.push([start, last]);
  return out
    .map(([a, b]) => ({ x0: x0 + a, x1: x0 + b + 1 }))
    .filter((g) => g.x1 - g.x0 >= minW)
    .map((g) => {
      let ty0 = y1, ty1 = y0;
      for (let y = y0; y < y1; y++)
        for (let x = g.x0; x < g.x1; x++) if (alphaFn(px(x, y)) > 0.5) { ty0 = Math.min(ty0, y); ty1 = Math.max(ty1, y + 1); }
      return { ...g, y0: ty0, y1: ty1 };
    });
}

async function trace(box, alphaFn, name) {
  const pad = 2;
  const x0 = box.x0 - pad, y0 = box.y0 - pad, w = box.x1 - box.x0 + pad * 2, h = box.y1 - box.y0 + pad * 2;
  const buf = Buffer.alloc(w * h);
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) buf[y * w + x] = Math.round(255 - alphaFn(px(x0 + x, y0 + y)) * 255); // dark = icon
  const S = 10;
  const big = await sharp(buf, { raw: { width: w, height: h, channels: 1 } })
    .resize(w * S, h * S, { kernel: "cubic" })
    .blur(S * 0.32)
    .png()
    .toBuffer();
  if (DEBUG) await sharp(big).toFile(path.join(DBG, `${name}.png`));
  const svg = await new Promise((res, rej) =>
    potrace.trace(big, { threshold: 128, turdSize: 12, optTolerance: 0.4, alphaMax: 1.1, blackOnWhite: true }, (e, s) => (e ? rej(e) : res(s))),
  );
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
  return { name, viewBox: `0 0 ${w * S} ${h * S}`, d, ratio: w / h };
}

const k = 1.03; // design was previewed at 735px; the file is 760px
const bands = {
  trust: { x0: Math.round(30 * k), x1: Math.round(362 * k), y0: Math.round(288 * k), y1: Math.round(316 * k), fn: redAlpha, gap: 5, names: ["people", "helmet", "shield", "support"] },
  why: { x0: Math.round(30 * k), x1: Math.round(470 * k), y0: Math.round(1046 * k), y1: Math.round(1072 * k), fn: redAlpha, gap: 12, names: ["rupee", "verified", "pin", "headset"] },
  stats: { x0: Math.round(30 * k), x1: Math.round(700 * k), y0: Math.round(1636 * k), y1: Math.round(1668 * k), fn: redAlpha, gap: 12, names: ["riders", "vehicles", "cities", "star", "shield100"], iconsOnly: 34 },
  uses: { x0: Math.round(30 * k), x1: Math.round(700 * k), y0: Math.round(704 * k), y1: Math.round(728 * k), fn: whiteAlpha, gap: 7, names: ["weekend", "business", "commute", "cities2"], iconsOnly: 34 },
};

const result = {};
for (const [bn, b] of Object.entries(bands)) {
  let gs = groups(b, b.fn, { gap: b.gap });
  if (b.iconsOnly) gs = gs.filter((g) => g.x1 - g.x0 <= b.iconsOnly && g.y1 - g.y0 >= 14);
  console.log(bn, gs.map((g) => `${g.x0},${g.y0} ${g.x1 - g.x0}x${g.y1 - g.y0}`).join(" | "));
  if (gs.length !== b.names.length) console.warn(`  !! expected ${b.names.length} icons, found ${gs.length}`);
  for (let i = 0; i < Math.min(gs.length, b.names.length); i++) {
    result[b.names[i]] = await trace(gs[i], b.fn, b.names[i]);
  }
}

const out =
  `// Generated by scripts/trace-icons.mjs from ref/design.png -- do not edit by hand.\n` +
  `export type TracedIcon = { viewBox: string; d: string };\n` +
  `export const tracedIcons: Record<string, TracedIcon> = ${JSON.stringify(
    Object.fromEntries(Object.entries(result).map(([n, r]) => [n, { viewBox: r.viewBox, d: r.d }])),
    null,
    1,
  )};\n`;
writeFileSync(path.join(ROOT, "app", "_lib", "traced-icons.ts"), out);
console.log("icons:", Object.keys(result).join(", "));
